import { describe, expect, it } from "vitest";
import {
  peakHourLabel,
  roadTypeLabel,
  trafficLevelLabel,
  trafficLevelLegend,
  trafficLevelScale,
  weatherLabel,
  weekdayLabel
} from "../../lib/labels";

describe("labels", () => {
  describe("weekdayLabel", () => {
    it("abbreviates the weekdays in Portuguese", () => {
      expect(
        ["MONDAY", "TUESDAY", "WEDNESDAY", "THURSDAY", "FRIDAY", "SATURDAY", "SUNDAY"].map(weekdayLabel)
      ).toEqual(["Seg", "Ter", "Qua", "Qui", "Sex", "Sáb", "Dom"]);
    });

    it("accepts lower case codes and keeps unknown values readable", () => {
      expect(weekdayLabel("monday")).toBe("Seg");
      expect(weekdayLabel("FERIADO_LOCAL")).toBe("Feriado Local");
    });
  });

  describe("roadTypeLabel", () => {
    it("names the road types in Portuguese", () => {
      expect(roadTypeLabel("LOCAL")).toBe("Via local");
      expect(roadTypeLabel("ARTERIAL")).toBe("Via arterial");
      expect(roadTypeLabel("HIGHWAY")).toBe("Via expressa");
      expect(roadTypeLabel("UNKNOWN")).toBe("Não informado");
    });

    it("keeps road types that are not in the list readable", () => {
      expect(roadTypeLabel("RURAL")).toBe("Rural");
      expect(roadTypeLabel("estrada_de_terra")).toBe("Estrada De Terra");
    });
  });

  describe("weatherLabel", () => {
    it("translates the weather codes generated by the simulation", () => {
      expect(weatherLabel("SUNNY")).toBe("Ensolarado");
      expect(weatherLabel("RAIN")).toBe("Chuva");
      expect(weatherLabel("CLOUDY")).toBe("Nublado");
      expect(weatherLabel("sunny")).toBe("Ensolarado");
    });

    it("leaves free text exactly as it was registered", () => {
      expect(weatherLabel("Céu limpo")).toBe("Céu limpo");
      expect(weatherLabel("Chuva forte")).toBe("Chuva forte");
    });
  });

  describe("trafficLevelLabel", () => {
    it("translates the traffic levels", () => {
      expect(trafficLevelLabel("LOW")).toBe("Baixo");
      expect(trafficLevelLabel("MEDIUM")).toBe("Médio");
      expect(trafficLevelLabel("HIGH")).toBe("Alto");
    });
  });

  describe("trafficLevelLegend", () => {
    // The reference is MapController in the backend (toTrafficLevel and toColor): up to 100 vehicles is LOW, up to
    // 200 is MEDIUM and above that is HIGH.
    it("fixes the limits and the colors the backend uses for the map", () => {
      expect(trafficLevelScale).toEqual([
        { level: "LOW", color: "#2BA36A", maxVolume: 100 },
        { level: "MEDIUM", color: "#FFB24A", maxVolume: 200 },
        { level: "HIGH", color: "#E04545", maxVolume: null }
      ]);
    });

    it("describes each color with its label and its range of vehicles", () => {
      expect(trafficLevelLegend()).toEqual([
        { level: "LOW", label: "Baixo", color: "#2BA36A", range: "até 100 veículos" },
        { level: "MEDIUM", label: "Médio", color: "#FFB24A", range: "de 101 a 200 veículos" },
        { level: "HIGH", label: "Alto", color: "#E04545", range: "acima de 200 veículos" }
      ]);
    });

    it("names the levels with the same words as the map popup", () => {
      expect(trafficLevelLegend().map((item) => item.label)).toEqual(
        ["LOW", "MEDIUM", "HIGH"].map(trafficLevelLabel)
      );
    });
  });

  describe("peakHourLabel", () => {
    it("shows the hour with the highest volume as 18h", () => {
      expect(peakHourLabel({ labels: ["08", "18", "12"], values: [120, 250, 80] })).toBe("18h");
    });

    it("drops the leading zero", () => {
      expect(peakHourLabel({ labels: ["08", "12"], values: [300, 80] })).toBe("8h");
      expect(peakHourLabel({ labels: ["00"], values: [5] })).toBe("0h");
    });

    it("keeps the earliest hour when volumes tie", () => {
      expect(peakHourLabel({ labels: ["09", "17"], values: [100, 100] })).toBe("9h");
    });

    it("says there is no data when there are no labels or every hour is zero", () => {
      expect(peakHourLabel({ labels: [], values: [] })).toBe("Sem dados");
      const hours = Array.from({ length: 24 }, (_, hour) => String(hour).padStart(2, "0"));
      expect(peakHourLabel({ labels: hours, values: hours.map(() => 0) })).toBe("Sem dados");
    });

    it("finds the peak among the 24 hours the backend returns", () => {
      const hours = Array.from({ length: 24 }, (_, hour) => String(hour).padStart(2, "0"));
      const values = hours.map((_, hour) => (hour === 18 ? 900 : 0));
      expect(peakHourLabel({ labels: hours, values })).toBe("18h");
    });
  });
});
